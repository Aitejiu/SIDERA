from __future__ import annotations

import subprocess
from pathlib import Path

import pytest

from sidera_control_plane.demo.sample_repository import (
    create_sample_repository,
    materialize_sample_stage,
)


def _test_command(repository: Path) -> subprocess.CompletedProcess[bytes]:
    return subprocess.run(
        ["python3", "-m", "unittest", "discover", "-s", "tests", "-v"],
        cwd=repository,
        capture_output=True,
        check=False,
    )


def test_sample_repository_is_owned_isolated_and_has_a_real_base_commit(
    tmp_path: Path,
) -> None:
    repository, base_commit = create_sample_repository(tmp_path)

    assert repository.is_dir()
    assert (repository / ".sidera-interview-demo-owner").read_text() == (
        "sidera-interview-demo-sample-v1\n"
    )
    assert repository.resolve() != Path(__file__).resolve().parents[4]
    assert subprocess.run(
        ["git", "remote"], cwd=repository, capture_output=True, check=True
    ).stdout == b""
    assert subprocess.run(
        ["git", "cat-file", "-t", base_commit],
        cwd=repository,
        capture_output=True,
        check=True,
    ).stdout.strip() == b"commit"


def test_sample_repository_base_commit_is_stable_across_runs(
    tmp_path: Path,
) -> None:
    _, first_commit = create_sample_repository(tmp_path)
    _, second_commit = create_sample_repository(tmp_path)

    assert first_commit == second_commit


def test_sample_repository_ignores_python_bytecode_created_by_checks(
    tmp_path: Path,
) -> None:
    repository, _ = create_sample_repository(tmp_path)
    cache_file = repository / "csv_importer" / "__pycache__" / "generated.pyc"
    cache_file.parent.mkdir()
    cache_file.write_bytes(b"generated bytecode")

    ignored = subprocess.run(
        ["git", "check-ignore", "--quiet", "csv_importer/__pycache__/generated.pyc"],
        cwd=repository,
        check=False,
    )

    assert ignored.returncode == 0


def test_unowned_or_project_internal_paths_are_rejected(tmp_path: Path) -> None:
    with pytest.raises(ValueError, match="owned sample repository"):
        materialize_sample_stage(tmp_path, "validation", True)

    sidera_root = Path(__file__).resolve().parents[4]
    with pytest.raises(ValueError, match="outside SIDERA"):
        create_sample_repository(sidera_root)


def test_sample_repository_parent_inside_a_user_git_repo_is_rejected(
    tmp_path: Path,
) -> None:
    user_repository = tmp_path / "user-project"
    user_repository.mkdir()
    subprocess.run(
        ["git", "init", "-q"], cwd=user_repository, check=True
    )

    with pytest.raises(ValueError, match="outside user Git repositories"):
        create_sample_repository(user_repository)

    assert list(user_repository.iterdir()) == [user_repository / ".git"]


def test_broken_and_repaired_outputs_have_real_exit_codes(tmp_path: Path) -> None:
    repository, _ = create_sample_repository(tmp_path)
    for stage in ("validation", "report", "integration", "broken"):
        changed = materialize_sample_stage(repository, stage, True)
        assert changed

    broken = _test_command(repository)
    assert broken.returncode != 0
    assert b"FAIL" in broken.stdout + broken.stderr or b"FAILED" in broken.stdout + broken.stderr

    materialize_sample_stage(repository, "repaired", True)
    repaired = _test_command(repository)
    assert repaired.returncode == 0, repaired.stderr.decode()


def test_optional_phone_rule_changes_the_real_report(tmp_path: Path) -> None:
    repository, _ = create_sample_repository(tmp_path)
    for stage in ("validation", "report", "integration"):
        materialize_sample_stage(repository, stage, True)

    completed = subprocess.run(
        [
            "python3",
            "-c",
            (
                "from csv_importer.importer import import_text; "
                "from pathlib import Path; "
                "result = import_text(Path('fixtures/contacts.csv').read_text(), "
                "phone_optional=True); "
                "assert result['report']['accepted'] == 2; "
                "assert result['report']['rejected'] == 2"
            ),
        ],
        cwd=repository,
        capture_output=True,
        check=False,
    )

    assert completed.returncode == 0, completed.stderr.decode()
